CREATE TABLE IF NOT EXISTS public.rol (
  id BIGINT PRIMARY KEY,
  tipo VARCHAR(80) NOT NULL UNIQUE
);

INSERT INTO public.rol (id, tipo)
VALUES
  (1, 'administrador'),
  (2, 'cliente_externo'),
  (3, 'socio'),
  (4, 'gerente'),
  (5, 'recepcionista')
ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.sede (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(150) NOT NULL
);

INSERT INTO public.sede (id, nombre)
VALUES (1, 'Sede de pruebas')
ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.plan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(150) NOT NULL UNIQUE,
  precio NUMERIC(10, 2) NOT NULL DEFAULT 0,
  intervalo VARCHAR(40) NOT NULL DEFAULT 'mensual',
  duracion_dias INTEGER NOT NULL DEFAULT 30,
  activo BOOLEAN NOT NULL DEFAULT TRUE
);

INSERT INTO public.plan (nombre)
VALUES ('Plan de pruebas de clases')
ON CONFLICT (nombre) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.usuario (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dni VARCHAR(80) NOT NULL UNIQUE,
  nombre VARCHAR(150) NOT NULL,
  contacto VARCHAR(255) NOT NULL,
  password TEXT NOT NULL,
  id_rol BIGINT NOT NULL REFERENCES public.rol(id),
  activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS public.suscripcion (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario BIGINT NOT NULL REFERENCES public.usuario(id) ON DELETE CASCADE,
  id_plan BIGINT NOT NULL REFERENCES public.plan(id),
  fecha_inicio DATE NOT NULL,
  fecha_fin DATE,
  estado VARCHAR(40) NOT NULL,
  fecha_proximo_vencimiento DATE
);
